// 챗봇이 처음부터 답할 수 있도록, 사이트에 이미 있는 내용으로 만든 기본 문서입니다.
// 관리자 화면의 "기본 문서 넣기" 버튼이 이 글을 지식베이스에 넣습니다.
// 사이트 내용이 바뀌면 문서를 지우고 다시 넣으면 됩니다.

import { teamMembers, projects, philosophy } from "./data";
import { SESSION, formatWon } from "./sauna-config";

export const SEED_TITLE = "REMO 기본 안내 (팀·프로젝트·사우나 치맥·사이트 이용)";
export const SEED_SOURCE = "사이트 내용 자동 생성";

export function buildSeedDocument(): string {
  const members = teamMembers
    .map((m) => `- ${m.name} (${m.role}): ${m.bio}`)
    .join("\n");

  const projectList = projects
    .map((p) => `- ${p.title} (${p.category}): ${p.description} 참여 팀원은 ${p.members.join(", ")}입니다.`)
    .join("\n");

  const values = philosophy.values.map((v) => `- ${v.title}: ${v.body}`).join("\n");

  return `# REMO 팀 소개

REMO는 "${philosophy.tagline}"(${philosophy.taglineEn})을 지향하는 팀입니다.
패션, 서비스 기획, 콘텐츠, 소프트웨어 등 서로 다른 관심사를 가진 팀원 ${teamMembers.length}명이 모여
각자의 프로젝트를 만들어가고 있습니다.

# 팀원

REMO의 팀원은 모두 ${teamMembers.length}명입니다.
${members}

# 진행 중인 프로젝트

REMO는 현재 ${projects.length}개의 프로젝트를 진행하고 있습니다.
${projectList}

# 팀의 철학

REMO가 일하는 방식은 이렇습니다. "${philosophy.quote}"
${values}

# 사우나 치맥 세션 개요

사우나 치맥은 REMO가 여는 소셜 세션입니다. 한 줄로 말하면 "${SESSION.tagline}"입니다.
처음 만나는 ${SESSION.capacity}명(남녀 절반씩)이 함께 찜질방에서 땀을 빼고, 근처 호프집에서 치킨과 맥주를 먹고 헤어지는 약 ${SESSION.durationHours}시간짜리 모임입니다.
장소는 서울이고, 평일 또는 금요일 저녁에 엽니다.
현재는 1호 세션을 열기 전 사전 수요 조사 단계입니다. 아직 정식으로 열리지 않았습니다.

# 사우나 치맥 가격과 포함 사항

정가는 ${formatWon(SESSION.priceRegular)}이고, 1호 세션에 한해 얼리버드 ${formatWon(SESSION.priceEarly)}입니다.
가격에 포함된 것은 찜질방 입장료, 찜질복과 수건, 치킨(4인당 1마리), 생맥주 2잔(무알콜로 바꿔도 가격 동일), 호스트 진행, 아이스브레이킹 키트, 질문 카드 세트입니다.
노쇼 방지 보증금 ${formatWon(SESSION.deposit)}이 있으며 참석하면 그대로 돌려드립니다.

# 사우나 치맥 진행 순서

19:00 체크인 (15분): 닉네임 스티커를 붙이고 규칙을 함께 읽습니다.
19:15 불가마 1라운드 (35분): 5분씩 두 번 들어가고, 중간에 나와서 식히며 대화합니다.
19:50 휴게실 토크 (30분): 질문 카드를 가지고 4명씩 두 조로 나눠 앉습니다.
20:20 샤워와 환복 (20분): 각자 씻고 옷을 갈아입은 뒤 입구에서 모입니다.
20:40 치맥 (70분): 도보 5분 거리 호프집에서, 중간에 한 번 자리를 바꿔 모두와 이야기합니다.
21:50 마무리 (10분): 연락처 교환은 전적으로 자율이며 호스트가 정리하고 해산합니다.

# 사우나 치맥 규칙과 안전

실명 확인 후 입장합니다. 예약 시 본인 확인을 합니다.
남녀 목욕탕은 따로입니다. 함께 있는 시간은 찜질복을 입은 공용 공간에서만 진행합니다.
술을 권하지 않습니다. 잔을 채워주는 문화가 없고, 무알콜이나 음료로 바꿔도 가격은 같습니다.
연락처를 먼저 요구하지 않습니다. 원하는 사람이 직접 건네는 것만 허용합니다.
호스트가 처음부터 끝까지 자리에 함께 있습니다.

# 사우나 치맥 자주 묻는 질문

혼자 가도 되는지: 네, 혼자 오는 것을 기준으로 설계한 세션입니다. 호스트가 첫 대화를 붙여드리고 질문 카드로 이어집니다.
사우나가 부담스러운 경우: 불가마 라운드는 선택입니다. 휴게실 토크부터 합류해도 되고, 중간에 나와서 쉬어도 됩니다.
성비: ${SESSION.capacity}명을 남녀 절반씩 모집합니다. 한쪽이 모자라면 날짜를 미루고 미리 안내합니다.
술을 못 마시는 경우: 무알콜 맥주나 음료로 바꿔드리고 가격은 같습니다. 치킨은 그대로 드셔도 됩니다.
환불: 세션 3일 전까지는 전액 환불입니다. 그 이후에는 대체 참석자를 찾아드리거나 다음 회차로 옮겨드립니다.

# 사우나 치맥 신청 방법

아직 정식 신청은 열리지 않았습니다. 사우나 치맥 페이지에서 참여 의향을 남기면 1호 세션이 열릴 때 가장 먼저 안내받습니다.
참여 의향은 "열리면 바로 신청", "관심 있음", "구경만" 중에 고를 수 있습니다.
개선 요청도 함께 남길 수 있고, 선택 설문(나이대, 성별, 지역, 선호 시간대, 희망 가격)에 답하면 커피 쿠폰 코드를 바로 받습니다. 쿠폰을 받으려면 이메일을 적어야 합니다.

# 사이트 이용 안내

사이트 첫 화면의 REMO 네 글자를 누르면 각 페이지로 갑니다. R은 팀 소개(Roots), E는 팀원 소개(Experts), M은 프로젝트(Making), O는 철학(Our Way)입니다.
게시판은 누구나 읽을 수 있지만, 글을 쓰려면 회원 가입 후 관리자 승인을 받아야 합니다.
가입 신청을 하면 승인 대기 상태가 되고, 관리자가 승인해야 로그인할 수 있습니다.
쓴 글은 본인과 관리자만 수정하거나 지울 수 있습니다.
답변받지 못한 질문은 게시판에 남기면 사람이 직접 답변합니다.`;
}
